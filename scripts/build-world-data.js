// Builds src/world-data.js: every NTS show we can reach, with where it broadcasts from,
// for the world view. Run now and then to pick up new shows: npm run world-data
//
// NTS's show list only pages through its first 1,000 shows, so the rest come from
// show search (by letter). Shows neither finds are left out.
const fs = require('fs');
const path = require('path');
const WorldPlaces = require('../src/world-places.js');

const API = 'https://www.nts.live/api/v2';
const get = async (url, tries = 3) => {
  for (let i = 0; i < tries; i++) {
    try {
      const r = await fetch(url);
      if (r.ok) return await r.json();
      if (r.status === 422) return {};               // offset past what NTS allows
    } catch {}
    await new Promise((res) => setTimeout(res, 1000 * (i + 1)));
  }
  return {};
};
async function pool(items, n, fn) {
  const out = []; let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < items.length) { const j = i++; out[j] = await fn(items[j]); } }));
  return out;
}

(async () => {
  const shows = new Map();      // alias -> [name, place]
  const offsets = []; for (let o = 0; o <= 1000; o += 12) offsets.push(o);
  for (const d of await pool(offsets, 6, (o) => get(`${API}/shows?offset=${o}&limit=12`))) {
    for (const s of d.results || []) shows.set(s.show_alias, [s.name, s.location_long || s.location_short || '']);
  }
  console.log(`show list: ${shows.size}`);
  const searches = [];
  for (const c of 'abcdefghijklmnopqrstuvwxyz0123456789') for (const o of [0, 50, 100, 150]) searches.push(`${API}/search?q=${c}&version=2&offset=${o}&limit=50&types[]=show`);
  let extra = 0;
  for (const d of await pool(searches, 6, get)) {
    for (const x of d.results || []) {
      const alias = (x.article?.path || '').split('/')[2];
      if (alias && !shows.has(alias)) { shows.set(alias, [x.title, x.location || '']); extra++; }
    }
  }
  console.log(`from search: ${extra} more, ${shows.size} in all`);
  if (shows.size < 500) { console.error('Too few shows: is the NTS API reachable?'); process.exit(1); }

  const unknown = new Map();
  for (const [, [, place]] of shows) {
    if (!WorldPlaces.find(place) && !WorldPlaces.isNowhere(place)) unknown.set(place, (unknown.get(place) || 0) + 1);
  }
  if (unknown.size) console.log('Places not in src/world-places.js (add them):', [...unknown].map(([p, n]) => `${p} (${n})`).join(', '));

  const rows = [...shows].sort((a, b) => a[0].localeCompare(b[0])).map(([alias, [name, place]]) => [alias, name, place]);
  const out = `// Generated by scripts/build-world-data.js on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand.\n`
    + `// Every NTS show we could reach: [show alias, name, where it broadcasts from]\n`
    + `const WORLD_SHOWS = ${JSON.stringify(rows)};\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'world-data.js'), out);
  console.log(`wrote src/world-data.js (${rows.length} shows)`);
})();
